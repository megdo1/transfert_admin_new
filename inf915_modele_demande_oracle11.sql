-- =====================================================================================
--  9. VUE DES JALONS
--     Pivote INF915_ACTION pour retrouver, en une ligne par demande, les dates et
--     acteurs clés. Remplace exactement les colonnes d'audit supprimées de l'en-tête,
--     en ajoutant ce qu'elles ne savaient pas porter : l'annulation et les relances.
-- =====================================================================================
CREATE OR REPLACE VIEW INF915_V_JALON AS
SELECT ID_NOTIFICATION,
       MIN(CASE WHEN TYPE_ACTION = 'CREATION'         THEN DATE_ACTION END) AS DATE_CREATION,
       MAX(CASE WHEN TYPE_ACTION = 'CREATION'         THEN ACTEUR      END) AS CREE_PAR,
       MAX(CASE WHEN TYPE_ACTION = 'ANNULATION'       THEN DATE_ACTION END) AS DATE_ANNULATION,
       MAX(CASE WHEN TYPE_ACTION = 'ANNULATION'       THEN ACTEUR      END) AS ANNULE_PAR,
       MAX(CASE WHEN TYPE_ACTION = 'ANNULATION'       THEN MOTIF       END) AS MOTIF_ANNULATION,
       MIN(CASE WHEN TYPE_ACTION = 'DEBUT_PARENTS'      THEN DATE_ACTION END) AS DATE_DEBUT_PARENTS,
       MAX(CASE WHEN TYPE_ACTION = 'FIN_PARENTS'        THEN DATE_ACTION END) AS DATE_FIN_PARENTS,
       MAX(CASE WHEN TYPE_ACTION = 'VALIDATION_PARENTS' THEN DATE_ACTION END) AS DATE_VALID_PARENTS,
       MAX(CASE WHEN TYPE_ACTION = 'VALIDATION_PARENTS' THEN ACTEUR      END) AS VALID_PARENTS_PAR,
       MIN(CASE WHEN TYPE_ACTION = 'DEBUT_LIGNES'       THEN DATE_ACTION END) AS DATE_DEBUT_LIGNES,
       MAX(CASE WHEN TYPE_ACTION = 'FIN_TRAITEMENT'     THEN DATE_ACTION END) AS DATE_FIN_TRT,
       SUM(CASE WHEN TYPE_ACTION = 'RELANCE'          THEN 1 ELSE 0    END) AS NB_RELANCES,
       MAX(CASE WHEN TYPE_ACTION = 'RELANCE'          THEN DATE_ACTION END) AS DATE_DER_RELANCE,
       MAX(CASE WHEN TYPE_ACTION = 'RELANCE'          THEN ACTEUR      END) AS DER_RELANCE_PAR
FROM   INF915_ACTION
GROUP  BY ID_NOTIFICATION;


-- =====================================================================================
--  10. VUE DE SUIVI  (écran RC360)
--      Les libellés d'organisation sont résolus par l'IHM à partir des identifiants.
-- =====================================================================================
CREATE OR REPLACE VIEW INF915_V_SUIVI AS
SELECT n.ID_NOTIFICATION,
       n.REFERENCE,
       NVL (o.LIBELLE, 'En attente de qualification')        AS LIB_OPERATION,
       n.MAILLE,
       n.ID_ORGA_SOURCE,
       NVL(n.ID_ORGA_CIBLE, n.ID_ORGA_SOURCE)                AS ID_ORGA_CIBLE,
       n.DATE_EFFET,
       n.STATUT,
       n.NB_LIGNES,
       n.NB_CONTRATS,
       n.NB_SI,
       n.NB_CF,
       n.NB_LOTS,
       n.NB_LIGNES_OK,
       n.NB_LIGNES_KO_METIER + n.NB_LIGNES_KO_TECH           AS NB_LIGNES_KO,
       CASE WHEN n.NB_LIGNES = 0 THEN 0
            ELSE ROUND(100 * n.NB_LIGNES_OK / n.NB_LIGNES, 1)
       END                                                    AS PCT_AVANCEMENT,
       n.NB_OBJETS_A_CREER,
       n.NB_OBJETS_CREES,
       j.DATE_CREATION,
       j.CREE_PAR,
       j.DATE_ANNULATION,
       j.ANNULE_PAR,
       j.MOTIF_ANNULATION,
       j.DATE_DEBUT_PARENTS,
       j.DATE_FIN_PARENTS,
       j.DATE_VALID_PARENTS,
       j.VALID_PARENTS_PAR,
       j.DATE_DEBUT_LIGNES,
       j.DATE_FIN_TRT,
       j.NB_RELANCES,
       j.DATE_DER_RELANCE,
       j.DER_RELANCE_PAR
FROM        INF915_NOTIFICATIONS n
LEFT   JOIN INF915_REF_OPERATION o ON o.CODE_OPERATION  = n.CODE_OPERATION
LEFT   JOIN INF915_V_JALON       j ON j.ID_NOTIFICATION = n.ID_NOTIFICATION;


-- =====================================================================================
--  11. VUE DE VOLUMÉTRIE RECALCULÉE
--      Équivalent des compteurs de l'en-tête, si vous préférez les supprimer.
-- =====================================================================================
CREATE OR REPLACE VIEW INF915_V_VOLUMETRIE AS
SELECT n.ID_NOTIFICATION,
       (SELECT COUNT(*) FROM INF915_LIGNE l
         WHERE l.ID_NOTIFICATION = n.ID_NOTIFICATION)                            AS NB_LIGNES,
       (SELECT COUNT(*) FROM INF915_LIGNE l
         WHERE l.ID_NOTIFICATION = n.ID_NOTIFICATION
           AND l.STATUT = 'TRANSFEREE')                                          AS NB_LIGNES_OK,
       (SELECT COUNT(*) FROM INF915_LIGNE l
         WHERE l.ID_NOTIFICATION = n.ID_NOTIFICATION
           AND l.STATUT IN ('ERREUR_METIER','ERREUR_TECHNIQUE'))                 AS NB_LIGNES_KO,
       (SELECT COUNT(*) FROM INF915_OBJET_PARENT p
         WHERE p.ID_NOTIFICATION = n.ID_NOTIFICATION
           AND p.TYPE_OBJET = 'CONTRAT')                                         AS NB_CONTRATS,
       (SELECT COUNT(*) FROM INF915_OBJET_PARENT p
         WHERE p.ID_NOTIFICATION = n.ID_NOTIFICATION
           AND p.TYPE_OBJET = 'SI')                                              AS NB_SI,
       (SELECT COUNT(*) FROM INF915_OBJET_PARENT p
         WHERE p.ID_NOTIFICATION = n.ID_NOTIFICATION
           AND p.TYPE_OBJET = 'CF')                                              AS NB_CF,
       (SELECT COUNT(*) FROM INF915_OBJET_PARENT p
         WHERE p.ID_NOTIFICATION = n.ID_NOTIFICATION
           AND p.TYPE_OBJET = 'LOT')                                             AS NB_LOTS,
       (SELECT COUNT(*) FROM INF915_OBJET_PARENT p
         WHERE p.ID_NOTIFICATION = n.ID_NOTIFICATION
           AND p.TYPE_CIBLE = 'CREATION')                                        AS NB_OBJETS_A_CREER
FROM   INF915_NOTIFICATIONS n;


