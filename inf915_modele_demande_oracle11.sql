-- =====================================================================================
--  7bis. TABLES TEMPORAIRES D'ACQUISITION
--
--  Interface d'entrée du service web de captation. Plutôt que de faire traverser des
--  dizaines de milliers d'identifiants par des collections PL/SQL, le service les
--  insère en masse dans ces deux tables temporaires, par lots JDBC, puis appelle
--  INF915_PY.PR_CREER_DEMANDE qui travaille en SQL ensembliste.
--
--  Sur cent mille lignes, la différence est décisive : une insertion par lots suivie de
--  quelques INSERT ... SELECT, contre cent mille allers-retours ou une collection de
--  cent mille éléments à sérialiser puis à parcourir.
--
--  ON COMMIT PRESERVE ROWS : le service peut valider entre deux lots sans perdre ce
--  qu'il a déjà inséré. Les lignes vivent le temps de la session et PR_CREER_DEMANDE
--  les purge en fin de traitement, réussite ou échec.
-- =====================================================================================

-- Le périmètre, désigné par identifiant fonctionnel et non par objid : le service web
-- raisonne en master id, c'est-à-dire en TABLE_CONTR_ITM.X_AV_ID_EDS. La résolution en
-- objid est faite par PR_CREER_DEMANDE.
--
-- Le rattachement accompagne chaque ligne plutôt que d'être passé en filtre global. La
-- raison est double. D'abord le parcours autorise plusieurs contrats, plusieurs sites
-- d'installation et plusieurs sites de facturation dans un même périmètre : un filtre
-- scalaire ne saurait pas l'exprimer. Ensuite et surtout, un master id peut exister sur
-- plusieurs BdS, et seul le rattachement exact de la ligne retenue lève l'ambiguïté.
-- La jointure devient ainsi une égalité stricte sur quatre colonnes, ce qui la rend à
-- la fois exacte et efficace sur de gros volumes.
--
-- Le service dispose de ces trois valeurs sans effort : ce sont celles qu'il a
-- affichées au conseiller en constituant la sélection.
CREATE GLOBAL TEMPORARY TABLE INF915_TMP_LIGNE (
  MASTER_ID             VARCHAR2(60)    NOT NULL,
  ID_CONTRAT_SOURCE     NUMBER(12)      NOT NULL,
  ID_SI_SOURCE          NUMBER(12)      NOT NULL,
  ID_CF_SOURCE          NUMBER(12)      NOT NULL
) ON COMMIT PRESERVE ROWS;

COMMENT ON TABLE INF915_TMP_LIGNE IS
  'Perimetre d une demande en cours de captation : un master id et son rattachement contrat, SI, CF. Alimentee par lots par le service web, lue puis purgee par INF915_PY.PR_CREER_DEMANDE.';
COMMENT ON COLUMN INF915_TMP_LIGNE.MASTER_ID IS
  'Identifiant fonctionnel de la ligne de service, rapproche de TABLE_CONTR_ITM.X_AV_ID_EDS.';

-- Le mapping : une ligne par objet parent qui ne reste pas identique à lui-même. Les
-- objets absents de cette table sont conservés tels quels.
