COMMENT ON COLUMN INF915_NOTIFICATIONS.ID_ORGA_CIBLE IS 'NULL si l organisation est conservee. Renseigne, la demande est un changement de titulaire.';

-- La liste de suivi se trie sur ID_NOTIFICATION DESC, qui suit l'ordre de création
-- puisqu'il vient d'une séquence. Aucun index sur une date de création n'est donc
-- nécessaire sur cette table.
--
-- =====================================================================================
--  CYCLE DE VIE D'UNE DEMANDE
--
--  Une demande n'existe en base que si elle est valide. La saisie et les contrôles
--  d'éligibilité ont lieu en amont, dans le service web synchrone d'acquisition :
--    - les brouillons ne sont pas stockés ici, ils vivent dans l'application appelante ;
--    - les contrôles sont joués avant l'écriture, et les lignes en échec sont rendues
--      au conseiller sans jamais entrer dans INF915_LIGNE ;
--    - il n'y a donc ni statut BROUILLON, ni statut CONTROLEE, ni étape de validation
--      distincte de la création. Écrire la demande, c'est la valider.
--
--          EN_ATTENTE ──────────────────────────────┐
--               │                                    │
--               ▼                (aucun objet à créer)
--       EN_COURS_PARENTS                             │
--               │                                    │
--      ┌────────┴─────────┐                          │
--      ▼                  ▼                          │
--   PARENTS_CREES ◄─ PARENTS_EN_ERREUR               │
--       │                  │  (correction, relance)  │
--       │  POINT D'ARRÊT : feu vert du métier        │
--       ▼                                            │
--   EN_ATTENTE_TRT_LIGNES                            │
--       │  (prise en charge d'un worker)             │
--  ═════│════════════════════════════════════════════│═════════════════════════
--       │        FRONTIÈRE D'IRRÉVERSIBILITÉ         │
--       ▼                                            ▼
--   EN_COURS_LIGNES ──┬──► TRAITEE
--          ▲          ├──► TRAITEE_PARTIELLE
--          │          └──► EN_ERREUR
--          └───────── (relance des lignes en échec)
--
--   ANNULEE ◄── EN_ATTENTE, PARENTS_CREES, PARENTS_EN_ERREUR, EN_ATTENTE_TRT_LIGNES
--               c'est-à-dire tous les statuts situés au-dessus de la frontière,
--               et eux seuls.
--
--  LE SEUL POINT D'ARRÊT
--  La phase séquentielle crée des contrats, des sites et des lots qui n'existaient pas.
--  Ces objets sont vérifiables et corrigeables tant qu'aucune BdS n'a bougé, et c'est
--  la seule chose que le métier ne peut pas contrôler avant, puisqu'elle n'existe pas
--  encore au moment de la saisie. La demande s'arrête donc là et attend une action
--  explicite, tracée dans INF915_ACTION sous le type VALIDATION_PARENTS. Aucun worker
--  ne franchit ce jalon tout seul.
--
--  Quand NB_OBJETS_A_CREER vaut zéro, il n'y a rien à vérifier : la demande passe
--  directement de EN_ATTENTE à EN_COURS_LIGNES. Le trigger autorise cette transition
--  pour ce seul cas et la refuse dès qu'un objet est à créer.
--
--  DEUX STATUTS D'ATTENTE, POUR LA MÊME RAISON
--  EN_ATTENTE et EN_ATTENTE_TRT_LIGNES séparent l'un et l'autre une décision de sa
--  prise en charge. Le métier valide, mais c'est le worker qui démarre, et il peut le
--  faire des heures plus tard. Sans ce statut intermédiaire, une demande dont le feu
--  vert vient d'être donné serait affichée « en cours » alors que rien ne tourne.
--
--  LA RÈGLE D'ANNULATION
--  ANNULEE est atteignable tant qu'aucune BdS n'a bougé, c'est-à-dire depuis
--  EN_ATTENTE, PARENTS_CREES, PARENTS_EN_ERREUR et EN_ATTENTE_TRT_LIGNES. Dès
--  EN_COURS_LIGNES, des BdS sont résiliées et recréées, et une annulation ne les
--  rétablirait pas : il ne reste que la relance des lignes en échec, ou la clôture en
--  TRAITEE_PARTIELLE puis TRAITEE. Le trigger fait respecter cette règle.
--
--  Une relance après échec repart directement en EN_COURS_LIGNES et non par
--  EN_ATTENTE_TRT_LIGNES : la demande est déjà engagée, il n'y a plus de feu vert à
--  donner, et faire repasser par un statut annulable rouvrirait une porte qui doit
--  rester fermée.
--
--  Nota : une annulation en PARENTS_CREES ne supprime pas les objets déjà créés dans
--  le parc. Le métier doit en disposer lui-même s'il le souhaite.
-- =====================================================================================


-- =====================================================================================
--  3. HISTORIQUE DE LA DEMANDE
--     Une ligne par action sur la demande, humaine ou automatique.
--     Remplace les colonnes CREE_PAR, DATE_CREATION, VALIDE_PAR, DATE_VALIDATION,
--     DATE_DEBUT_TRT et DATE_FIN_TRT de l'en-tête, qui ne savaient représenter
--     ni l'annulation, ni les relances successives.
-- =====================================================================================
CREATE TABLE INF915_ACTION (
  ID_ACTION             NUMBER(12)      NOT NULL,   -- alimenté par TRG_INF915_ACTION_BI
  ID_NOTIFICATION       NUMBER(12)      NOT NULL,

  TYPE_ACTION           VARCHAR2(20)    NOT NULL,
  ACTEUR                VARCHAR2(40)    NOT NULL,   -- login, ou identifiant du worker
  TYPE_ACTEUR           VARCHAR2(12)    NOT NULL,   -- UTILISATEUR | SYSTEME
  DATE_ACTION           TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,

  -- Transition de statut provoquée par l'action, quand il y en a une
  STATUT_AVANT          VARCHAR2(22),
  STATUT_APRES          VARCHAR2(22),

  -- Portée, utile sur les relances partielles : combien de lignes ont été relancées,
  -- et sur quel critère. Le détail ligne par ligne est dans INF915_EVENEMENT,
  -- dont les lignes portent l'ID_ACTION.
  NB_LIGNES_VISEES      NUMBER(8),
  PORTEE                VARCHAR2(40),               -- TOUTES | ERREUR_TECH | ERREUR_METIER | SELECTION

  -- Motif d'annulation, commentaire de relance, cause d'un échec système
  MOTIF                 VARCHAR2(500),

  CONSTRAINT PK_INF915_ACTION       PRIMARY KEY (ID_ACTION),
  CONSTRAINT FK_INF915_ACTION_NOT   FOREIGN KEY (ID_NOTIFICATION)
      REFERENCES INF915_NOTIFICATIONS (ID_NOTIFICATION) ON DELETE CASCADE,
  CONSTRAINT CK_INF915_ACTION_TYPE  CHECK (TYPE_ACTION IN (
      'CREATION',            -- écriture de la demande, contrôles déjà passés en amont
      'DEBUT_PARENTS',       -- prise en charge de la phase séquentielle
      'FIN_PARENTS',         -- objets parents créés, demande en attente du feu vert
      'VALIDATION_PARENTS',  -- feu vert du métier après vérification des objets créés
      'DEBUT_LIGNES',        -- prise en charge de la phase parallèle
      'FIN_TRAITEMENT',      -- fin de traitement, partielle ou complète
      'ANNULATION',          -- demande abandonnée, qui et pourquoi
      'RELANCE')),           -- relance de lignes en erreur, qui et sur quelle portée
  CONSTRAINT CK_INF915_ACTION_ACTEU CHECK (TYPE_ACTEUR IN ('UTILISATEUR','SYSTEME')),
  CONSTRAINT CK_INF915_ACTION_PORT  CHECK (PORTEE IS NULL OR PORTEE IN
      ('TOUTES','ERREUR_TECH','ERREUR_METIER','SELECTION')),
  -- une annulation doit être motivée
  CONSTRAINT CK_INF915_ACTION_MOTIF CHECK (TYPE_ACTION <> 'ANNULATION' OR MOTIF IS NOT NULL),
  -- une relance doit dire ce qu'elle vise
  CONSTRAINT CK_INF915_ACTION_RELAN CHECK (TYPE_ACTION <> 'RELANCE' OR PORTEE IS NOT NULL)
);

CREATE INDEX IX_INF915_ACTION_NOT ON INF915_ACTION (ID_NOTIFICATION, DATE_ACTION);
CREATE INDEX IX_INF915_ACTION_ACT ON INF915_ACTION (ACTEUR, DATE_ACTION);
CREATE INDEX IX_INF915_ACTION_TYP ON INF915_ACTION (TYPE_ACTION, DATE_ACTION);

-- Une demande n'a qu'une création et qu'une annulation. Index unique fonctionnel :
-- les lignes dont l'expression est NULL ne sont pas indexées, la contrainte ne porte
-- donc que sur les actions du type visé.
CREATE UNIQUE INDEX UX_INF915_ACTION_CREA ON INF915_ACTION
  (CASE WHEN TYPE_ACTION = 'CREATION'   THEN ID_NOTIFICATION END);
CREATE UNIQUE INDEX UX_INF915_ACTION_ANNU ON INF915_ACTION
  (CASE WHEN TYPE_ACTION = 'ANNULATION' THEN ID_NOTIFICATION END);

COMMENT ON TABLE INF915_ACTION IS
  'Historique de la demande : qui a cree, qui a valide les objets parents, qui a annule et pourquoi, qui a relance et sur quelle portee. La creation vaut validation : les controles sont passes en amont par le service d acquisition.';
COMMENT ON COLUMN INF915_ACTION.TYPE_ACTEUR IS
  'UTILISATEUR pour une action humaine, SYSTEME pour une action de worker ou d ordonnanceur. Permet de filtrer l historique metier du bruit technique.';
COMMENT ON COLUMN INF915_ACTION.PORTEE IS
  'Sur une relance : quelles lignes ont ete visees. Le detail ligne par ligne se retrouve dans INF915_EVENEMENT via ID_ACTION.';


