-- Garde-fou sur les transitions de statut. Empêche un worker ou un correctif de
-- faire sauter le point d'arrêt, ou de rouvrir une demande close.
CREATE OR REPLACE TRIGGER TRG_INF915_NOTIF_BU
BEFORE UPDATE OF STATUT ON INF915_NOTIFICATIONS
FOR EACH ROW
WHEN (OLD.STATUT <> NEW.STATUT)
DECLARE
  c_ok CONSTANT VARCHAR2(1000) :=
    '|EN_ATTENTE>EN_COURS_PARENTS' || '|EN_ATTENTE>EN_COURS_LIGNES'       ||
    '|EN_ATTENTE>ANNULEE'          ||
    '|EN_COURS_PARENTS>PARENTS_CREES'    || '|EN_COURS_PARENTS>PARENTS_EN_ERREUR' ||
    '|PARENTS_EN_ERREUR>EN_COURS_PARENTS'|| '|PARENTS_EN_ERREUR>PARENTS_CREES'    ||
    '|PARENTS_EN_ERREUR>ANNULEE'   ||
    '|PARENTS_CREES>EN_ATTENTE_TRT_LIGNES'   || '|PARENTS_CREES>ANNULEE'          ||
    '|EN_ATTENTE_TRT_LIGNES>EN_COURS_LIGNES' || '|EN_ATTENTE_TRT_LIGNES>ANNULEE'  ||
    '|EN_COURS_LIGNES>TRAITEE'     || '|EN_COURS_LIGNES>TRAITEE_PARTIELLE' ||
    '|EN_COURS_LIGNES>EN_ERREUR'   ||
    '|EN_ERREUR>EN_COURS_LIGNES'   || '|EN_ERREUR>TRAITEE_PARTIELLE'       ||
    '|TRAITEE_PARTIELLE>EN_COURS_LIGNES' || '|TRAITEE_PARTIELLE>TRAITEE'   || '|';
BEGIN
  IF INSTR (c_ok, '|' || :OLD.STATUT || '>' || :NEW.STATUT || '|') = 0 THEN
    RAISE_APPLICATION_ERROR (-20917,
      'INF915 : transition de statut interdite, ' || :OLD.STATUT || ' -> ' || :NEW.STATUT);
  END IF;

  -- Le point d'arrêt ne se saute que si rien n'a été créé.
  IF :OLD.STATUT = 'EN_ATTENTE' AND :NEW.STATUT = 'EN_COURS_LIGNES'
     AND NVL (:NEW.NB_OBJETS_A_CREER, 0) > 0 THEN
    RAISE_APPLICATION_ERROR (-20918,
      'INF915 : ' || :NEW.NB_OBJETS_A_CREER || ' objet(s) a creer, la demande doit ' ||
      'passer par EN_COURS_PARENTS puis PARENTS_CREES.');
  END IF;
END;
/

