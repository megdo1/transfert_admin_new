-- =====================================================================================
--  TRANSFERT DE PARC UNIFIÉ — MODÈLE DE PERSISTANCE DE LA DEMANDE
--  Cible : Oracle 11g R2. Acquisition synchrone Java, workers asynchrones Python,
--          packages PL/SQL.
--
--    INF915_REF_OPERATION   le référentiel des opérations déduites
--    INF915_NOTIFICATIONS   l'en-tête : qui, quoi, quand
--    INF915_ACTION          l'historique de la demande : création, validation,
--                           annulation, relance, début et fin de traitement
--    INF915_OBJET_PARENT    les objets parents du périmètre et leur cible
--    INF915_LIGNE           le périmètre lui-même, une ligne par IDS
--    INF915_CONTROLE        pourquoi une ligne a été exclue
--    INF915_EVENEMENT       le journal d'exécution, ligne par ligne
--
--  DEUX HISTORIQUES, DEUX GRANULARITÉS
--    INF915_ACTION porte l'histoire de la DEMANDE : quelques lignes par demande,
--    un acteur identifié, une portée métier. C'est ce que l'écran de suivi affiche
--    dans le panneau « historique », et ce que l'audit conserve des années.
--    INF915_EVENEMENT porte le journal des LIGNES et des objets parents : plusieurs
--    dizaines de milliers de lignes pour une grosse demande, purgeable après quelques
--    mois sans rien perdre de la traçabilité métier.
--    Les deux sont reliés : un événement produit par une relance porte l'ID_ACTION
--    de cette relance, ce qui permet de retrouver quelles lignes une relance donnée
--    a effectivement touchées.
--
--  ADAPTATIONS 11g PAR RAPPORT À UNE ÉCRITURE 12c
--    - pas de colonne IDENTITY : une séquence et un trigger BEFORE INSERT par table,
--      avec le test IS NULL qui reproduit la sémantique GENERATED BY DEFAULT ;
--    - le référentiel est créé en premier, la clé étrangère de l'en-tête le référence ;
--    - aucune contrainte IS JSON, aucun DEFAULT ON NULL, aucune colonne virtuelle ;
--    - tous les identifiants tiennent dans 30 caractères.
--
--  LE TRAITEMENT EST PILOTÉ PAR LA DONNÉE, PAS PAR L'ACTE
--  Aucun traitement ne lit CODE_OPERATION pour décider quoi faire. Le worker lit
--  INF915_OBJET_PARENT pour savoir quels objets créer ou réutiliser, puis
--  INF915_LIGNE pour savoir quelles BdS déplacer et vers quel rattachement. Ces deux
--  tables suffisent, quel que soit l'acte. CODE_OPERATION n'existe que pour le
--  reporting, l'écran de suivi et la comparaison avec les huit actes historiques.
--  Il est calculé après coup par le worker Python via INF915_PY, il est
--  facultatif, et une qualification erronée n'a aucune conséquence sur le transfert.
--  C'est la raison pour laquelle INF915_REF_OPERATION ne porte pas de nom de package
--  de traitement : il n'y a pas un package par acte, il y a un seul traitement.
--
--  RÈGLE DE NORMALISATION
--  Seuls les identifiants techniques sont stockés. Les libellés, numéros de contrat,
--  SITE_ID et noms de lot restent dans le référentiel Clarify et sont résolus à
--  l'affichage. La restitution d'une demande ancienne affiche donc les libellés
--  d'aujourd'hui, et la requête d'affichage doit joindre TABLE_CONTRACT, TABLE_SITE
--  ou TABLE_CONTR_SCHEDULE selon INF915_OBJET_PARENT.TYPE_OBJET.
--
--  SEULE EXCEPTION : les compteurs de INF915_NOTIFICATIONS, pour que l'écran de suivi
--  affiche une liste de demandes sans agréger à chaud. Ils sont toujours mis à jour en
--  incrémental (SET NB = NB + 1). La vue INF915_V_VOLUMETRIE donne l'équivalent
--  recalculé si vous préférez les supprimer.
--
--  PRINCIPES ISSUS DE L'ANALYSE DE L'EXISTANT
--    1. Aucune colonne dont le sens dépend du type d'acte (leçon de X_AV_FOCUS_ID).
--    2. Les objid sont résolus une seule fois, à la validation, et figés (leçon de
--       ChmtCF, qui résout les sites par SITE_ID à chaque passage du batch).
--    3. Pas de demande fille : les lignes rattachées à un accès entrent dans
--       INF915_LIGNE avec un lien vers leur porteuse (leçon de ChmtCFAccesFull).
--    4. Deux phases d'exécution, deux tables : INF915_OBJET_PARENT pilote la phase
--       séquentielle, INF915_LIGNE la phase parallèle.
--    5. Ne sont pas stockés : les remises, recalculées par le rattachement de la
--       version commerciale à la grille du contrat cible, et les options de niveau
--       ligne, transférées telles quelles.
-- =====================================================================================


